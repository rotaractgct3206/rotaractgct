export const getFlagshipBySlug = (slug) => flagships.find((f) => f.slug === slug);

export const flagshipTenures = ['2026-27', '2025-26', '2024-25', '2023-24', '2022-23'];

export const getFlagshipsByTenure = (tenure) => {
  return flagships.filter(flagship => 
    flagship.editions.some(edition => edition.tenure === tenure)
  ).map(flagship => {
    const edition = flagship.editions.find(ed => ed.tenure === tenure);
    return { ...flagship, currentEdition: edition };
  });
};
